# -*- coding: utf-8 -*-
"""修复 node_modules 中被安全策略删掉/未完整解压的文件。

背景：本机 WorkBuddy 沙箱会拦截 Node 侧的文件删除/写入，导致 npm 解压部分
包时丢失文件（表现为 package.json main/exports 指向的文件不存在）。
本脚本直接走 HTTP 拉取对应版本 tarball，并用 Python 原生 IO 覆盖写回。

用法:
    python tools/repair_node_modules.py            # 体检 + 修复
    python tools/repair_node_modules.py --check    # 只体检
"""
from __future__ import annotations

import io
import json
import shutil
import subprocess
import sys
import tarfile
import tempfile
import urllib.request
from pathlib import Path

REGISTRY = "https://registry.npmmirror.com"
ROOT = Path(__file__).resolve().parent.parent
NM = ROOT / "node_modules"


def load_meta(pkg_dir: Path):
    pj = pkg_dir / "package.json"
    if not pj.exists():
        return None
    try:
        return json.loads(pj.read_text(encoding="utf-8"))
    except Exception:
        return None


def entry_files(meta: dict) -> list[str]:
    """收集 main / exports 指向的文件"""
    entries: list[str] = []
    if isinstance(meta.get("main"), str):
        entries.append(meta["main"])
    ex = meta.get("exports")
    if isinstance(ex, str):
        entries.append(ex)
    elif isinstance(ex, dict):
        for v in ex.values():
            if isinstance(v, str):
                entries.append(v)
            elif isinstance(v, list):
                entries += [x for x in v if isinstance(x, str)]
            elif isinstance(v, dict):
                for sub in v.values():
                    if isinstance(sub, str):
                        entries.append(sub)
                    elif isinstance(sub, list):
                        entries += [x for x in sub if isinstance(x, str)]
    return [e[2:] if e.startswith("./") else e for e in entries]


def tarball_url(meta: dict) -> str | None:
    name = meta.get("name")
    version = meta.get("version")
    if not name or not version:
        return None
    base = name.split("/")[-1]
    if "/" in name:  # scoped
        scope = name.split("/")[0]
        return f"{REGISTRY}/{scope}/{base}/-/{base}-{version}.tgz"
    return f"{REGISTRY}/{name}/-/{name}-{version}.tgz"


def fetch_tarball(url: str, dest: Path) -> bool:
    try:
        with urllib.request.urlopen(url, timeout=60) as resp:
            dest.write_bytes(resp.read())
        return True
    except Exception as exc:  # noqa: BLE001
        print(f"    ! 下载失败 {url}: {exc}")
        return False


def extract_over(tgz: Path, pkg_dir: Path) -> int:
    """把 tarball 内 package/ 的内容覆盖到 pkg_dir"""
    written = 0
    with tarfile.open(tgz, "r:gz") as tf:
        for member in tf.getmembers():
            if not member.isfile():
                continue
            name = member.name.split("package/", 1)[-1]
            if not name or name.startswith("..") or name.startswith("/"):
                continue
            target = pkg_dir / name
            target.parent.mkdir(parents=True, exist_ok=True)
            data = tf.extractfile(member)
            if data is None:
                continue
            try:
                target.write_bytes(data.read())
                written += 1
            except Exception as exc:  # noqa: BLE001
                print(f"    ! 写失败 {name}: {exc}")
    return written


def scan() -> list[tuple[Path, dict]]:
    dirs = [p for p in NM.iterdir() if p.is_dir()]
    for nested in NM.rglob("node_modules"):
        dirs += [p for p in nested.iterdir() if p.is_dir()]

    broken = []
    for pkg in dirs:
        meta = load_meta(pkg)
        if not meta:
            continue
        missing = [e for e in entry_files(meta) if not (pkg / e).exists()]
        if missing:
            broken.append((pkg, meta))
    return broken


def main() -> None:
    check_only = "--check" in sys.argv
    if not NM.exists():
        sys.exit("node_modules 不存在，请先 npm install")

    broken = scan()
    print(f"扫描完成：异常包 {len(broken)} 个")
    if not broken or check_only:
        for pkg, _ in broken:
            print(f"  - {pkg.relative_to(NM)}")
        return

    for pkg, meta in broken:
        rel = pkg.relative_to(NM)
        url = tarball_url(meta)
        if not url:
            print(f"  ! {rel}: 无法确定 tarball 地址")
            continue
        print(f"  * 修复 {rel} ({meta.get('version')})")
        with tempfile.TemporaryDirectory() as tmp:
            tgz = Path(tmp) / "pkg.tgz"
            if not fetch_tarball(url, tgz):
                continue
            n = extract_over(tgz, pkg)
            print(f"    -> 写回 {n} 个文件")

    print("修复完成")


if __name__ == "__main__":
    main()
